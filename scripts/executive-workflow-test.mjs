import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFile } from 'node:fs/promises';
import { chromium } from 'playwright-core';

const baseUrl = process.env.AIIO_BASE_URL ?? 'http://127.0.0.1:3002';
const browser = await chromium.launch({ executablePath: process.env.CHROME_EXECUTABLE ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const context = await browser.newContext({ acceptDownloads: true, reducedMotion: 'reduce' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
try {
  await page.goto(baseUrl, { waitUntil: 'networkidle' });
  await page.getByRole('slider', { name: 'Selected project month', exact: true }).fill('14');
  const month = await page.getByRole('slider', { name: 'Selected project month', exact: true }).getAttribute('aria-valuetext');
  await page.getByRole('button', { name: /Pin current configuration/ }).click();
  await page.getByRole('button', { name: 'Guided story', exact: true }).click();
  await page.getByRole('button', { name: /02Monthly exposure|02 Monthly exposure/ }).click();
  assert.equal(await page.getByRole('slider', { name: 'Briefing month', exact: true }).inputValue(), '14');
  await page.getByRole('button', { name: /03Why it happens|03 Why it happens/ }).click();
  const driverButtons = page.locator('button[aria-pressed]');
  const driver = driverButtons.nth(1);
  const driverText = (await driver.innerText()).split('\n')[0];
  await driver.click();
  await page.getByRole('button', { name: 'Monthly outlook', exact: true }).click();
  assert.equal(await page.getByRole('slider', { name: 'Selected project month', exact: true }).getAttribute('aria-valuetext'), month);
  assert.ok((await page.locator('button[aria-pressed="true"]').allTextContents()).some((text) => text.includes(driverText)));
  await page.getByRole('button', { name: 'Evidence lens', exact: true }).click();
  await page.getByRole('button', { name: /Public projects/ }).click();
  assert.match(await page.locator('#selected-evidence').innerText(), /Alberta/);
  await page.getByRole('button', { name: 'Open decision brief', exact: true }).click();
  const brief = page.locator('#executive-decision-brief');
  assert.equal(await brief.count(), 1);
  assert.match(await brief.innerText(), /Pinned alternative/);
  assert.ok((await brief.innerText()).includes(month));
  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download snapshot', exact: true }).click();
  const download = await pending;
  const envelope = JSON.parse(await readFile(await download.path(), 'utf8'));
  assert.match(execFileSync(process.execPath, ['scripts/verify-assessment-snapshot.mjs', await download.path()], { encoding: 'utf8' }), /cashflow reproduced/);
  assert.equal(createHash('sha256').update(envelope.payload).digest('hex'), envelope.sha256);
  const record = JSON.parse(envelope.payload);
  assert.equal(record.focus.month, month);
  assert.equal(record.comparison.scenario_spend_delta_millions, 0);
  assert.ok(Math.abs(record.result.combinedSpend - record.result.monthly.reduce((sum, row) => sum + row.combinedSpend, 0)) < 1e-8);
  await page.emulateMedia({ media: 'print' });
  assert.equal(await brief.evaluate((element) => getComputedStyle(element).visibility), 'visible');
  assert.equal(await page.getByRole('button', { name: 'Download snapshot', exact: true, includeHidden: true }).evaluate((element) => getComputedStyle(element).visibility), 'hidden');
  await page.emulateMedia({ media: 'screen' });
  await page.getByRole('button', { name: 'Share inputs', exact: true }).click();
  const shared = page.url();
  assert.equal(new URL(shared).searchParams.get('profile'), 'bell');
  await page.goto(shared, { waitUntil: 'networkidle' });
  assert.equal(await page.getByRole('spinbutton', { name: 'Base budget ($M)', exact: true }).inputValue(), '1200');
  await page.locator('input[type="month"]').fill('2041-01');
  await page.getByRole('button', { name: 'Open decision brief', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Download snapshot', exact: true }).isDisabled(), true);
  assert.match(await brief.innerText(), /withheld/);
  assert.deepEqual(errors, []);
  console.log('Executive workflow passed: shared focus, evidence navigation, brief, snapshot checksum, print visibility, input link restore and invalid-input withholding.');
} finally { await context.close(); await browser.close(); }
